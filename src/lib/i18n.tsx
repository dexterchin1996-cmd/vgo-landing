export type TransKey = keyof typeof TRANSLATIONS.zh;

const LangCtx = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TransKey) => string;
}>({
  lang: "zh",
  setLang: () => {},
  t: (k) => TRANSLATIONS.zh[k],
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("zh");

  // 记住用户选择
  useEffect(() => {
    const saved = typeof window !== "undefined" ? localStorage.getItem("vgo_lang") : null;
    if (saved === "zh" || saved === "en" || saved === "ms") setLangState(saved);
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("vgo_lang", l);
  };

  const t = (k: TransKey) => TRANSLATIONS[lang][k] ?? TRANSLATIONS.zh[k];

  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);
